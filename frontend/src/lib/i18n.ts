export const locale = writable<Locale>('en');

export function getLocaleTag(value: Locale): string {
  return value === 'it' ? 'it-IT' : 'en-US';
}

function normalizeLocale(value: string | null | undefined): Locale {
  if (!value) return 'en';
  const normalized = value.toLowerCase().slice(0, 2) as Locale;
  if (supportedLocales.includes(normalized)) return normalized;
  return 'en';
}

function updateDocumentLanguage(value: Locale) {
  if (!isBrowser) return;
  document.documentElement.lang = value;
}

export function initializeLocale() {
  if (!isBrowser) return;

  const stored = localStorage.getItem(STORAGE_KEY);
  const next = stored ? normalizeLocale(stored) : normalizeLocale(navigator.language);
  locale.set(next);
}

export function setLocale(next: Locale) {
  locale.set(next);
  if (!isBrowser) return;
  localStorage.setItem(STORAGE_KEY, next);
}

locale.subscribe((value) => {
  updateDocumentLanguage(value);
});

export function t(value: Locale, key: string, params?: Record<string, string | number>): string {
  const fromActive = translations[value][key];
  const fromFallback = translations.en[key];
  const template = fromActive ?? fromFallback ?? key;

  if (!params) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? `{${token}}`));
}
